#!/usr/bin/env node
// Generates js/config.js from environment variables.
// Runs automatically on Vercel via the build command in vercel.json.
// Run locally with: npm run build:config  (after filling .env.local)

const fs = require('fs');
const path = require('path');

// Minimal .env.local loader (no dependency needed)
function loadEnvLocal() {
  const envPath = path.join(__dirname, '..', '.env.local');
  if (!fs.existsSync(envPath)) return;
  const lines = fs.readFileSync(envPath, 'utf8').split('\n');
  lines.forEach(line => {
    const m = line.match(/^\s*([\w.]+)\s*=\s*(.*)?\s*$/);
    if (m && !process.env[m[1]]) {
      process.env[m[1]] = (m[2] || '').replace(/^["']|["']$/g, '');
    }
  });
}
loadEnvLocal();

const required = ['VITE_SUPABASE_URL', 'VITE_SUPABASE_ANON_KEY'];
const missing = required.filter(k => !process.env[k]);
if (missing.length) {
  console.warn('⚠️  Missing env vars (using placeholders): ' + missing.join(', '));
  console.warn('   Set them in Vercel → Settings → Environment Variables,');
  console.warn('   or in .env.local for local development.');
}

const out = `// AUTO-GENERATED by scripts/generate-config.js — do not edit directly.
// Edit .env.local (dev) or Vercel Environment Variables (prod) instead.
window.APP_CONFIG = {
  SUPABASE_URL: ${JSON.stringify(process.env.VITE_SUPABASE_URL || 'https://your-project-ref.supabase.co')},
  SUPABASE_ANON_KEY: ${JSON.stringify(process.env.VITE_SUPABASE_ANON_KEY || 'your-anon-public-key-here')},
  AUTHORIZED_EMAIL: ${JSON.stringify(process.env.AUTHORIZED_EMAIL || 'nagaraju@example.com')},
  GOOGLE_CALENDAR_CLIENT_ID: ${JSON.stringify(process.env.GOOGLE_CALENDAR_CLIENT_ID || '')}
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'js', 'config.js'), out);
console.log('✅ js/config.js generated');
